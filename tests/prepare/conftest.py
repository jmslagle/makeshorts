def make_words(*specs: tuple[str, float, float]) -> WordsDoc:
    """`WordsDoc` from `(text, start, end)` triples, with sentence flags applied
    by the real segmenter."""
    from makeshorts.prepare.transcribe import mark_sentence_boundaries

    words = [Word(text=t, start=s, end=e) for t, s, e in specs]
    return WordsDoc(model="test", language="en", words=mark_sentence_boundaries(words))


def evenly_timed(text: str, *, start: float = 0.0, per_word: float = 0.4) -> WordsDoc:
    """A WordsDoc from a sentence, one word every `per_word` seconds."""
    specs = []
    t = start
    for token in text.split():
        specs.append((token, round(t, 3), round(t + per_word * 0.8, 3)))
        t += per_word
    return make_words(*specs)
