"""Synthesised media fixtures.

Everything the mechanical stage is tested against is generated by `ffmpeg
-f lavfi` at test time. No binary fixture is committed: a webinar clip is large,
opaque, and impossible to review in a diff, and the properties these tests
assert (duration, resolution, where the silence is) are exactly the properties
lavfi lets us state up front.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest

from makeshorts.artifacts import Word, WordsDoc

FFMPEG = shutil.which("ffmpeg") or "/opt/homebrew/bin/ffmpeg"

requires_ffmpeg = pytest.mark.skipif(
    not Path(FFMPEG).exists(), reason="ffmpeg not installed"
)


def run_ffmpeg(args: list[str]) -> None:
    proc = subprocess.run(
        [FFMPEG, "-nostdin", "-hide_banner", "-y", *args],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:  # pragma: no cover - only on a broken ffmpeg
        raise RuntimeError(f"fixture generation failed:\n{proc.stderr[-2000:]}")


@pytest.fixture(scope="session")
def av_file(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """6s, 320x240, 30fps, one audio channel, silent from 2.0s to 4.0s.

    The silent window is produced by gating the sine rather than concatenating,
    so the file has one continuous audio stream and the silence is genuinely
    mid-file.
    """
    out = tmp_path_factory.mktemp("media") / "av.mp4"
    run_ffmpeg(
        [
            "-f", "lavfi", "-i", "testsrc2=size=320x240:rate=30:duration=6",
            "-f", "lavfi", "-i", "sine=frequency=440:duration=6:sample_rate=44100",
            "-filter_complex", "[1:a]volume=enable='between(t,2,4)':volume=0,pan=mono|c0=c0[a]",
            "-map", "0:v", "-map", "[a]",
            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac",
            "-t", "6", str(out),
        ]
    )
    return out


